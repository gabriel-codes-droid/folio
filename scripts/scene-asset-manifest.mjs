import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const models = new URL('../public/models/', import.meta.url);
const assets = readdirSync(models).sort().map(name => {
  const data = readFileSync(new URL(name, models));
  return { url: `/models/${name}`, bytes: data.length, version: createHash('sha256').update(data).digest('hex').slice(0, 16) };
});
writeFileSync(new URL('../src/data/sceneAssets.js', import.meta.url),
  `// Generated by scripts/scene-asset-manifest.mjs. Do not edit by hand.\nexport const SCENE_ASSETS = ${JSON.stringify(assets, null, 2)};\n`);
console.log(`Scene manifest: ${assets.length} assets, ${assets.reduce((sum, asset) => sum + asset.bytes, 0)} bytes`);
